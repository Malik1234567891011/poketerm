"""Bake sprite data into the Ghostty shader and the shell's encounter art.

shaders/*.src.glsl -> shaders/*.glsl   (//@PARTY marker)
art/pmd/<name>/portrait-*.png -> shell/sprites/<NAME>.<mood>.ans
"""
import os
import pathlib

from PIL import Image

import pmd

ROOT = pathlib.Path(__file__).resolve().parent.parent


def party_names():
    """party.conf holds 1-3 species, or "random" (the default): then the
    partner rolled for this session is read from .partner (see poketerm.zsh)."""
    conf = ROOT / "party.conf"
    names = conf.read_text().split() if conf.exists() else ["random"]
    if names == ["random"]:
        cur = ROOT / ".partner"
        names = cur.read_text().split() if cur.exists() else ["pikachu"]
    if (ROOT / ".try").exists():  # `poke try NAME`: one species, for the next tab only
        names = (ROOT / ".try").read_text().split()
    if os.environ.get("POKETERM_PARTY"):  # preview a party without touching party.conf
        names = os.environ["POKETERM_PARTY"].split()
    names = [n.lower() for n in names if n.lower() in pmd.ROSTER][:3]
    return names or ["pikachu"]


def glsl_party(names):
    words, pal = [], []
    fr_off, fr_w, fr_h, fr_x0, fr_y0, fr_t = [], [], [], [], [], []
    an_start, an_n, an_len = [], [], []
    ground, half_w, top, ghost = [], [], [], []
    for name in names:
        anims = pmd.load(name)
        colors, index = pmd.palette(anims)
        pal += [(0, 0, 0)] + colors + [(0, 0, 0)] * (15 - len(colors))
        lo_y, max_x, max_y = 10 ** 6, 0, 0
        for anim in pmd.ANIMS:
            an_start.append(len(fr_off))
            an_n.append(len(anims[anim]))
            t = 0.0
            for img, cx, cy, secs in anims[anim]:
                bb = img.getbbox() or (0, 0, 1, 1)
                crop = img.crop(bb)
                w, h = crop.size
                x0, y0 = bb[0] - int(cx), int(cy) - bb[3]
                if anim == "Walk":
                    lo_y = min(lo_y, y0)
                if anim in ("Walk", "Idle"):
                    max_x = max(max_x, abs(x0), abs(x0 + w))
                    max_y = max(max_y, y0 + h)
                wpr = (w + 7) // 8
                fr_off.append(len(words))
                fr_w.append(w); fr_h.append(h); fr_x0.append(x0); fr_y0.append(y0)
                px = crop.load()
                for y in range(h):
                    for wi in range(wpr):
                        v = 0
                        for i in range(8):
                            x = wi * 8 + i
                            if x < w:
                                v |= index(px[x, y]) << (i * 4)
                        words.append(v)
                t += secs
                fr_t.append(t)
            an_len.append(t)
        ground.append(lo_y); half_w.append(max_x); top.append(max_y - lo_y)
        ghost.append(name in pmd.GHOSTS)

    def arr(typ, name, vals, fmt=str):
        body = ",\n    ".join(", ".join(fmt(v) for v in vals[i:i + 12]) for i in range(0, len(vals), 12))
        return f"const {typ} {name}[{len(vals)}] = {typ}[](\n    {body});"

    pad = lambda xs, fill: xs + [fill] * (3 - len(xs))
    pika = [i for i, n in enumerate(names) if n == "pikachu"]
    lines = [
        f"// party: {' '.join(names)}  — generated by tools/build.py (edit party.conf or run `poke party ...`)",
        "// sprites: PMD SpriteCollab (CC BY-NC 4.0), credits in art/pmd/*/credits.txt",
        f"#define PARTY_N {len(names)}",
        f"#define PARTY_HAS_JIGGLY {'true' if 'jigglypuff' in names else 'false'}",
        f"#define PARTY_HAS_DARKRAI {'true' if 'darkrai' in names else 'false'}",
        f"#define PARTY_HAS_SNORLAX {'true' if 'snorlax' in names else 'false'}",
        f"#define PARTY_ELECTRIC {'true' if {'pikachu', 'voltorb'} & set(names) else 'false'}",
        "\n".join(f"#define SP_{n.upper()} {i}" for i, n in enumerate(pmd.ROSTER)),
        "#define A_WALK 0\n#define A_IDLE 1\n#define A_SLEEP 2\n#define A_HOP 3\n#define A_HURT 4\n#define A_SPECIAL 5",
        "#define IS_PIKACHU(k) (" + (" || ".join(f"(k) == {i}" for i in pika) or "false") + ")",
        "#define IS_JIGGLY(k) (" + (" || ".join(f"(k) == {i}" for i, n in enumerate(names) if n == "jigglypuff") or "false") + ")",
        arr("uint", "SPR", words, lambda v: f"0x{v:08x}u"),
        arr("int", "FR_OFF", fr_off), arr("int", "FR_W", fr_w), arr("int", "FR_H", fr_h),
        arr("int", "FR_X0", fr_x0), arr("int", "FR_Y0", fr_y0),
        arr("float", "FR_T", fr_t, lambda v: f"{v:.4f}"),
        arr("int", "AN_START", an_start), arr("int", "AN_N", an_n),
        arr("float", "AN_LEN", an_len, lambda v: f"{v:.4f}"),
        arr("int", "S_GROUND", pad(ground, 0)),
        arr("int", "S_HALFW", pad(half_w, half_w[0])),
        arr("int", "S_TOP", pad(top, top[0])),
        arr("bool", "S_GHOST", pad(ghost, False), lambda v: "true" if v else "false"),
        arr("int", "S_SPECIES", pad([list(pmd.ROSTER).index(n) for n in names], -1)),
        arr("vec3", "PAL", pal, lambda c: f"vec3({c[0] / 255:.3f}, {c[1] / 255:.3f}, {c[2] / 255:.3f})"),
    ]
    print(f"party {names}: {len(words)} sprite words, {len(fr_off)} frames")
    return "\n".join(lines)


def ansi_rows(img):
    """RGBA image -> truecolor half-block lines (2 pixel rows per line)."""
    img = img.convert("RGBA")
    w, h = img.size
    px = img.load()
    col = lambda x, y: px[x, y][:3] if y < h and px[x, y][3] > 127 else None
    rows = []
    for y in range(0, h, 2):
        out = []
        for x in range(w):
            top, bot = col(x, y), col(x, y + 1)
            if top and bot:
                out.append("\x1b[38;2;%d;%d;%dm\x1b[48;2;%d;%d;%dm▀" % (top + bot))
            elif top:
                out.append("\x1b[0m\x1b[38;2;%d;%d;%dm▀" % top)
            elif bot:
                out.append("\x1b[0m\x1b[38;2;%d;%d;%dm▄" % bot)
            else:
                out.append("\x1b[0m ")
        rows.append("".join(out) + "\x1b[0m")
    return rows


def ansi_portraits():
    out = ROOT / "shell" / "sprites"
    out.mkdir(parents=True, exist_ok=True)
    for old in out.glob("*.ans"):
        old.unlink()
    for name in pmd.ROSTER:
        for mood in ("Normal", "Happy", "Joyous", "Pain"):
            p = pmd.PMD / name / f"portrait-{mood}.png"
            if p.exists():
                (out / f"{name.upper()}.{mood.lower()}.ans").write_text("\n".join(ansi_rows(Image.open(p))) + "\n")


def main():
    import sys
    if "--shader-only" not in sys.argv:
        ansi_portraits()
    party = glsl_party(party_names())
    for src in (ROOT / "shaders").glob("*.src.glsl"):
        out = src.with_name(src.name.replace(".src.glsl", ".glsl"))
        if os.environ.get("POKETERM_PARTY"):  # previews never touch the shader Ghostty loads
            out = ROOT / "preview" / out.name
            out.parent.mkdir(exist_ok=True)
        out.write_text(src.read_text().replace("//@PARTY", party).replace("//@SPRITES", ""))
        print("built", out.relative_to(ROOT))


if __name__ == "__main__":
    main()
